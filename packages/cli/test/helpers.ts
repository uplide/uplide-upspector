import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { detectProject } from "../src/context.js";
import type { Step, StepResult } from "../src/step.js";
import { Workspace } from "../src/workspace.js";

export const PACKAGE_JSON = JSON.stringify({
  dependencies: { next: "16.4.2", react: "19.2.4", "react-dom": "19.2.4" },
});

export const LAYOUT = `import type { Metadata } from "next";
import { Geist } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body className={\`\${geistSans.variable} antialiased\`}>
        {children}
      </body>
    </html>
  );
}
`;

export const NEXT_CONFIG = `import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  /* config options here */
};

export default nextConfig;
`;

/**
 * A temp project holding `files`, plus `package.json`, `tsconfig.json` and,
 * unless `files` has its own `app/`, `src/` or `pages/`, `app/layout.tsx`.
 */
export function createProject(files: Record<string, string> = {}): string {
  const root = mkdtempSync(join(tmpdir(), "upspector-cli-"));
  const all: Record<string, string> = {
    "package.json": PACKAGE_JSON,
    "tsconfig.json": "{}",
    ...(Object.keys(files).some((path) => /^(app|src|pages)\//.test(path))
      ? {}
      : { "app/layout.tsx": LAYOUT }),
    ...files,
  };
  for (const [path, text] of Object.entries(all)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

export function readProjectFile(root: string, path: string): string {
  return readFileSync(join(root, path), "utf8");
}

/** Runs one step against a project and returns its result and the files it wrote. */
export function runStep(
  step: Step,
  files: Record<string, string> = {},
): { result: StepResult; written: Record<string, string> } {
  const workspace = new Workspace(createProject(files));
  const result = step.run({ ...detectProject(workspace), apiEnv: "NEXT_PUBLIC_API_BASE_URL" });
  const written = Object.fromEntries(
    workspace.changes().map(({ path, after }) => [path, after]),
  );
  return { result, written };
}
